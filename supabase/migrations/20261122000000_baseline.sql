CREATE VIEW ctf.challenge_points WITH (security_invoker=true) AS
 WITH solve_counter AS (
         SELECT solves.challenge_id,
            (count(*))::integer AS solve_count
           FROM ctf.solves
          GROUP BY solves.challenge_id
        )
 SELECT c.id,
    c.title,
    c.category,
    c.prompt,
    c.files,
    c.is_active,
    c.prerequisite_id,
    c.initial_points,
    c.min_points,
    c.decay_solves,
    COALESCE(sc.solve_count, 0) AS solve_count,
        CASE
            WHEN (COALESCE(sc.solve_count, 0) <= 1) THEN c.initial_points
            WHEN (sc.solve_count >= c.decay_solves) THEN c.min_points
            ELSE GREATEST(c.min_points, (c.initial_points - (floor(((((c.initial_points - c.min_points))::numeric / (NULLIF((c.decay_solves - 1), 0))::numeric) * ((sc.solve_count - 1))::numeric)))::integer))
        END AS current_points
   FROM (ctf.challenges c
     LEFT JOIN solve_counter sc ON ((sc.challenge_id = c.id)));

