CREATE OR REPLACE FUNCTION trpg.apply_curse_sync(p_channel_id text, p_expected_cursor text, p_new_cursor text, p_deltas jsonb)
 RETURNS boolean
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
DECLARE
  v_current text;
BEGIN
  -- One run per channel at a time; released when the transaction ends
  PERFORM pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtext('curse_sync:' || p_channel_id));

  SELECT last_message_id INTO v_current FROM trpg.sync_cursors WHERE channel_id = p_channel_id;
  IF COALESCE(v_current, '0') <> p_expected_cursor THEN
    RETURN false;
  END IF;

  INSERT INTO trpg.curse_stats (user_id, username, year, count, total_messages, updated_at)
  SELECT d.user_id, d.username, d.year, d.curses, d.messages, pg_catalog.now()
  FROM pg_catalog.jsonb_to_recordset(p_deltas)
    AS d(user_id text, username text, year integer, curses integer, messages integer)
  ON CONFLICT (user_id, year) DO UPDATE SET
    username = EXCLUDED.username,
    count = trpg.curse_stats.count + EXCLUDED.count,
    total_messages = trpg.curse_stats.total_messages + EXCLUDED.total_messages,
    updated_at = pg_catalog.now();

  INSERT INTO trpg.sync_cursors (channel_id, last_message_id, updated_at)
  VALUES (p_channel_id, p_new_cursor, pg_catalog.now())
  ON CONFLICT (channel_id) DO UPDATE SET
    last_message_id = EXCLUDED.last_message_id,
    updated_at = pg_catalog.now();

  RETURN true;
END;
$function$
;

CREATE OR REPLACE FUNCTION trpg.get_quaso_leaderboard(p_mode text, p_limit integer DEFAULT 10)
 RETURNS TABLE(user_id text, username text, total bigint)
 LANGUAGE plpgsql
 SET search_path TO 'trpg', 'public'
AS $function$
BEGIN
    IF p_mode = 'sent' THEN
        -- 送出最多 (大善人榜)
        RETURN QUERY
        SELECT 
            giver_id AS user_id,
            (ARRAY_AGG(giver_name ORDER BY created_at DESC))[1] AS username,
            SUM(amount) AS total
        FROM trpg.quaso_transactions
        GROUP BY giver_id
        ORDER BY total DESC
        LIMIT p_limit;
    ELSE
        -- 收到最多 (團寵人氣榜，預設)
        RETURN QUERY
        SELECT 
            receiver_id AS user_id,
            (ARRAY_AGG(receiver_name ORDER BY created_at DESC))[1] AS username,
            SUM(amount) AS total
        FROM trpg.quaso_transactions
        GROUP BY receiver_id
        ORDER BY total DESC
        LIMIT p_limit;
    END IF;
END;
$function$
;

CREATE OR REPLACE FUNCTION trpg.give_quaso(p_giver_id text, p_giver_name text, p_receiver_id text, p_receiver_name text, p_amount integer)
 RETURNS json
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'trpg', 'public'
AS $function$
DECLARE
    v_today_used INT;
    v_remaining INT;
BEGIN
    IF p_giver_id = p_receiver_id THEN
        RETURN json_build_object('success', false, 'message', '❌ 你不能把 Quaso 送給自己！請把美味分享給其他群友。');
    END IF;

    -- 查詢今日已送出數量
    SELECT COALESCE(SUM(amount), 0) INTO v_today_used
    FROM trpg.quaso_transactions
    WHERE giver_id = p_giver_id AND give_date = CURRENT_DATE;

    v_remaining := 3 - v_today_used;

    IF v_remaining <= 0 THEN
        RETURN json_build_object('success', false, 'message', '🛑 閣下今日的 3 枚 Quaso 額度已全數用盡，請待午夜刷新！');
    END IF;

    IF p_amount > v_remaining THEN
        RETURN json_build_object('success', false, 'message', format('⚠️ 額度不足！今日僅剩 %s 枚 Quaso 可送出。', v_remaining));
    END IF;

    -- 寫入流水帳 (攜帶最新使用者名稱)
    INSERT INTO trpg.quaso_transactions (giver_id, giver_name, receiver_id, receiver_name, amount, give_date)
    VALUES (p_giver_id, p_giver_name, p_receiver_id, p_receiver_name, p_amount, CURRENT_DATE);

    RETURN json_build_object(
        'success', true, 
        'remaining', v_remaining - p_amount,
        'message', format('🥐 成功投遞 %s 枚 Quaso 給 **%s**！', p_amount, p_receiver_name)
    );
END;
$function$
;

