        ), filtered_players AS (
         SELECT pts.account_id,
            pts.tournament_bind_id,
            pts.total_pts,
            pts.games_played
           FROM (player_tournament_stats pts
             JOIN mahjong.tournaments t ON ((pts.tournament_bind_id = t.id)))
