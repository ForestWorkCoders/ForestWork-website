        ), tournament_ranks AS (
         SELECT filtered_players.account_id,
            filtered_players.tournament_bind_id,
            filtered_players.total_pts,
            filtered_players.games_played,
            rank() OVER (PARTITION BY filtered_players.tournament_bind_id ORDER BY filtered_players.total_pts DESC) AS final_rank
           FROM filtered_players
        )
 SELECT tr.account_id,
    tr.tournament_bind_id,
    fc.year,
    fc.month,
    COALESCE(((fc.points_map ->> (tr.final_rank)::text))::integer, 0) AS points,
    tr.total_pts AS raw_score,
    tr.games_played AS played_rounds,
    tr.final_rank AS month_rank
   FROM (tournament_ranks tr
     JOIN mahjong.fwmp_configs fc ON ((tr.tournament_bind_id = fc.tournament_bind_id)))
  WHERE (COALESCE(((fc.points_map ->> (tr.final_rank)::text))::integer, 0) > 0);

