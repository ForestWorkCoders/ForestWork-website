CREATE OR REPLACE FUNCTION mahjong.get_player_meetup_frequency(p_start_time timestamp with time zone DEFAULT '2026-07-01 00:00:00+00'::timestamp with time zone, p_tournament_id uuid DEFAULT NULL::uuid)
 RETURNS TABLE(player1 integer, player1_name text, player2 integer, player2_name text, meet_up_count bigint)
 LANGUAGE plpgsql
 SET search_path TO 'mahjong', 'public'
AS $function$
BEGIN
    RETURN QUERY
    WITH match_players AS (
        -- 将 matches 横向的 (east, south, west, north) 展平为纵向，自动过滤 NULL 与人机
        SELECT m.id AS match_id, m.east_id AS player_id FROM mahjong.matches m
        WHERE (p_tournament_id IS NULL OR m.tournament_bind_id = p_tournament_id)
          AND (p_start_time IS NULL OR m.start_time >= p_start_time)
          AND m.east_id IS NOT NULL AND m.east_id <> 1
        UNION ALL
        SELECT m.id AS match_id, m.south_id AS player_id FROM mahjong.matches m
        WHERE (p_tournament_id IS NULL OR m.tournament_bind_id = p_tournament_id)
          AND (p_start_time IS NULL OR m.start_time >= p_start_time)
          AND m.south_id IS NOT NULL AND m.south_id <> 1
        UNION ALL
        SELECT m.id AS match_id, m.west_id AS player_id FROM mahjong.matches m
        WHERE (p_tournament_id IS NULL OR m.tournament_bind_id = p_tournament_id)
          AND (p_start_time IS NULL OR m.start_time >= p_start_time)
          AND m.west_id IS NOT NULL AND m.west_id <> 1
        UNION ALL
        SELECT m.id AS match_id, m.north_id AS player_id FROM mahjong.matches m
        WHERE (p_tournament_id IS NULL OR m.tournament_bind_id = p_tournament_id)
          AND (p_start_time IS NULL OR m.start_time >= p_start_time)
          AND m.north_id IS NOT NULL AND m.north_id <> 1
    ),
    player_pairs AS (
        -- 优雅自连接：a.player_id < b.player_id 自动保证无序二元组唯一，不漏掉任何一家
        SELECT 
            a.player_id AS p1,
            b.player_id AS p2
        FROM match_players a
        JOIN match_players b 
          ON a.match_id = b.match_id 
         AND a.player_id < b.player_id
    )
    SELECT
        pp.p1 AS player1,
        COALESCE(part1.nickname, 'Unknown_' || pp.p1::text) AS player1_name,
        pp.p2 AS player2,
        COALESCE(part2.nickname, 'Unknown_' || pp.p2::text) AS player2_name,
        COUNT(*) AS meet_up_count
    FROM player_pairs pp
    LEFT JOIN mahjong.participants part1 ON pp.p1 = part1.account_id
    LEFT JOIN mahjong.participants part2 ON pp.p2 = part2.account_id
    GROUP BY pp.p1, part1.nickname, pp.p2, part2.nickname
    ORDER BY meet_up_count DESC;
END;
$function$
;

CREATE OR REPLACE FUNCTION mahjong.get_player_recent_ranks(p_player_id integer, matches_count integer DEFAULT 20)
 RETURNS integer[]
 LANGUAGE plpgsql
 SET search_path TO 'mahjong', 'public'
AS $function$
DECLARE
    result_ranks integer[];
BEGIN
    WITH recent_matches AS (
        -- 1. 快速索引定位：先按时间倒序锁定该玩家参与的最近 N 场比赛
        SELECT id, start_time, east_id, east_score, south_id, south_score, west_id, west_score, north_id, north_score
        FROM mahjong.matches
        WHERE p_player_id IN (east_id, south_id, west_id, north_id)
        ORDER BY start_time DESC
        LIMIT matches_count
    ),
    unpivoted_scores AS (
        -- 2. 解表：优雅展开为选手-得分对，自动过滤人机与三麻空北位
        SELECT 
            m.id AS match_id,
            m.start_time,
            p.player_id,
            p.score,
            RANK() OVER (PARTITION BY m.id ORDER BY p.score DESC)::integer AS calculated_rank
        FROM recent_matches m
        CROSS JOIN LATERAL (
            VALUES 
                (m.east_id, m.east_score),
                (m.south_id, m.south_score),
                (m.west_id, m.west_score),
                (m.north_id, m.north_score)
        ) AS p(player_id, score)
        WHERE p.player_id IS NOT NULL AND p.score IS NOT NULL
    )
    -- 3. 提取目标玩家在该批对局中的顺位，按时间倒序聚合成数组
    SELECT ARRAY_AGG(calculated_rank ORDER BY start_time DESC)
    INTO result_ranks
    FROM unpivoted_scores
    WHERE player_id = p_player_id;

    RETURN COALESCE(result_ranks, ARRAY[]::integer[]);
END;
$function$
;

CREATE OR REPLACE FUNCTION mahjong.get_seat_frequency(p_start_time timestamp with time zone DEFAULT '2026-07-01 00:00:00+00'::timestamp with time zone, p_tournament_id uuid DEFAULT NULL::uuid)
 RETURNS TABLE(account_id integer, mahjong_username text, east bigint, south bigint, west bigint, north bigint)
 LANGUAGE plpgsql
 SET search_path TO 'mahjong', 'public'
AS $function$
BEGIN
    RETURN QUERY
    WITH seat_actions AS (
        -- 单次解表，将 4 个座位展平为 (player_id, seat_name)
        SELECT 
            p.player_id,
            p.seat_name
        FROM mahjong.matches m
        CROSS JOIN LATERAL (
            VALUES 
                (m.east_id, 'east'),
                (m.south_id, 'south'),
                (m.west_id, 'west'),
                (m.north_id, 'north')
        ) AS p(player_id, seat_name)
        WHERE (p_tournament_id IS NULL OR m.tournament_bind_id = p_tournament_id)
          AND (p_start_time IS NULL OR m.start_time >= p_start_time)
          AND p.player_id IS NOT NULL 
          AND p.player_id <> 1 -- 过滤掉系统占位/人机账号
    )
    SELECT 
        sa.player_id AS account_id,
        COALESCE(part.nickname, 'Unknown_' || sa.player_id::text) AS mahjong_username,
        COUNT(*) FILTER (WHERE sa.seat_name = 'east') AS east,
        COUNT(*) FILTER (WHERE sa.seat_name = 'south') AS south,
        COUNT(*) FILTER (WHERE sa.seat_name = 'west') AS west,
        COUNT(*) FILTER (WHERE sa.seat_name = 'north') AS north
    FROM seat_actions sa
    LEFT JOIN mahjong.participants part ON sa.player_id = part.account_id
    GROUP BY sa.player_id, part.nickname
    ORDER BY sa.player_id;
END;
$function$
;

CREATE OR REPLACE FUNCTION mahjong.get_tournament_match_stats(t_id uuid, p_phase text DEFAULT NULL::text)
 RETURNS TABLE(player_id integer, nickname text, avatar text, play_count integer, avg_rank numeric, east_count integer, avg_rank_east numeric, south_count integer, avg_rank_south numeric, west_count integer, avg_rank_west numeric, north_count integer, avg_rank_north numeric, rank_1_count integer, top_rate_pct numeric, rank_2_count integer, top2_rate_pct numeric, rank_3_count integer, avoid_last_rate_pct numeric, rank_4_count integer, busting_rate numeric, avg_score numeric, highest_point numeric, lowest_point numeric)
 LANGUAGE sql
 SET search_path TO 'mahjong', 'public'
AS $function$
WITH unpivoted_matches AS (
  SELECT
    m.id AS match_id,
    v.player_id,
    v.score,
    v.seat_name,
    RANK() OVER (PARTITION BY m.id ORDER BY v.score DESC) as rank
  FROM mahjong.matches m
  CROSS JOIN LATERAL (
    VALUES
      ('East', m.east_id, m.east_score),
      ('South', m.south_id, m.south_score),
      ('West', m.west_id, m.west_score),
      ('North', m.north_id, m.north_score)
  ) AS v(seat_name, player_id, score)
  WHERE m.tournament_bind_id = t_id
    AND (p_phase IS NULL OR m.group_tag = p_phase)
    AND v.player_id IS NOT NULL -- 过滤掉三麻的空北风位
    AND v.player_id != 1
)
SELECT
  u.player_id,
  p.nickname,
  pd.profile_img AS avatar,
  COUNT(score) AS play_count,
  ROUND(AVG(u.rank)::numeric, 2) AS avg_rank,
  COUNT(CASE WHEN u.seat_name = 'East' THEN 1 END) AS east_count,
  ROUND(AVG(CASE WHEN u.seat_name = 'East' THEN u.rank END)::numeric, 2) AS avg_rank_east,
  COUNT(CASE WHEN u.seat_name = 'South' THEN 1 END) AS south_count,
  ROUND(AVG(CASE WHEN u.seat_name = 'South' THEN u.rank END)::numeric, 2) AS avg_rank_south,
  COUNT(CASE WHEN u.seat_name = 'West' THEN 1 END) AS west_count,
  ROUND(AVG(CASE WHEN u.seat_name = 'West' THEN u.rank END)::numeric, 2) AS avg_rank_west,
  COUNT(CASE WHEN u.seat_name = 'North' THEN 1 END) AS north_count,
  ROUND(AVG(CASE WHEN u.seat_name = 'North' THEN u.rank END)::numeric, 2) AS avg_rank_north,
  COUNT(CASE WHEN rank = 1 THEN 1 END) AS rank_1_count,
  ROUND(COUNT(CASE WHEN u.rank = 1 THEN 1 END) * 100.0 / COUNT(u.score), 2) AS top_rate_pct,
  COUNT(CASE WHEN rank = 2 THEN 1 END) AS rank_2_count,
  ROUND(COUNT(CASE WHEN u.rank IN (1, 2) THEN 1 END) * 100.0 / COUNT(u.score), 2) AS top2_rate_pct,
  COUNT(CASE WHEN rank = 3 THEN 1 END) AS rank_3_count,
  ROUND(COUNT(CASE WHEN u.rank != 4 THEN 1 END) * 100.0 / COUNT(u.score), 2) AS avoid_last_rate_pct,
  COUNT(CASE WHEN rank = 4 THEN 1 END) AS rank_4_count,
  ROUND(COUNT(CASE WHEN u.score < 0 THEN 1 END) * 100.0 / COUNT(u.score), 2) AS busting_rate_pct,
  ROUND((AVG(u.score)::numeric - 35000)/1000, 1) AS avg_score,
  ROUND(MAX((score::numeric - 35000)/1000), 1) AS highest_point,
  ROUND(MIN((score::numeric - 35000)/1000), 1) AS lowest_point
FROM unpivoted_matches u
JOIN mahjong.participants p ON u.player_id = p.account_id
LEFT JOIN public.participant_data pd ON p.discord_id = pd.discord_id
GROUP BY u.player_id, p.nickname, pd.profile_img
ORDER BY avg_rank ASC;
$function$
;

CREATE OR REPLACE FUNCTION mahjong.get_tournament_playstyle_stats(t_id uuid, p_phase text DEFAULT NULL::text)
 RETURNS TABLE(player_id integer, nickname text, avatar text, total_rounds bigint, win_rate numeric, deal_in_rate numeric, tsumo_rate numeric, dama_rate numeric, exhaustive_draw_rate numeric, draw_tenpai_rate numeric, call_rate numeric, riichi_rate numeric, avg_turns numeric, avg_win_score numeric, avg_deal_in_score numeric, avg_baopai numeric, li_baopai_rate_pct numeric, babei_rate_pct numeric)
 LANGUAGE sql
 SET search_path TO 'mahjong', 'public'
AS $function$
WITH player_rounds AS (
    SELECT
      m.id AS match_id,
      pr.id AS round_id,
      v.seat_index,
      v.player_id,
      pr.won_seat,
      pr.ron_seat,
      pr.won_type,
      pr.win_turn,
      (pr.delta_scores ->> v.seat_index)::numeric AS delta_score,
      (pr.riichi_status ->> v.seat_index)::int AS is_riichi,
      (pr.fulo_status ->> v.seat_index)::int AS is_fulo,
      (pr.draw_tenpai ->> v.seat_index)::int AS is_tenpai,
      COALESCE((pr.won_yaku ->> '31')::int, 0) AS count_dora,
      COALESCE((pr.won_yaku ->> '32')::int, 0) AS count_akadora,
      COALESCE((pr.won_yaku ->> '33')::int, 0) AS count_uradora,
      COALESCE((pr.won_yaku ->> '34')::int, 0) AS count_kitadora,
      COALESCE((pr.babei_status ->> v.seat_index)::int, 0) AS babei_count
    FROM mahjong.matches m
    JOIN mahjong.paipu_rounds pr ON m.uuid = pr.paipu_id
    CROSS JOIN LATERAL (
      VALUES
        (0, m.east_id),
        (1, m.south_id),
        (2, m.west_id),
        (3, m.north_id)
    ) AS v(seat_index, player_id)
    WHERE m.tournament_bind_id = t_id
      AND (p_phase IS NULL OR m.group_tag = p_phase)
      AND v.player_id IS NOT NULL
      AND v.player_id != 1
  )
  SELECT
    u.player_id,
    p.nickname,
    pd.profile_img AS avatar,
    COUNT(u.round_id) AS total_rounds,
    ROUND(COUNT(CASE WHEN u.won_seat = u.seat_index THEN 1 END) * 100.0 / COUNT(u.round_id), 2) AS win_rate,
    ROUND(COUNT(CASE WHEN u.ron_seat = u.seat_index THEN 1 END) * 100.0 / COUNT(u.round_id), 2) AS deal_in_rate,
    ROUND(COUNT(CASE WHEN u.won_seat = u.seat_index AND u.won_type = 'zimo' THEN 1 END) * 100.0 /
          NULLIF(COUNT(CASE WHEN u.won_seat = u.seat_index THEN 1 END), 0), 2) AS tsumo_rate,
    ROUND(COUNT(CASE WHEN u.won_seat = u.seat_index AND u.is_riichi = 0 AND u.is_fulo = 0 THEN 1 END) * 100.0 /
          NULLIF(COUNT(CASE WHEN u.won_seat = u.seat_index THEN 1 END), 0), 2) AS dama_rate,
    ROUND(COUNT(CASE WHEN u.won_type = 'draw' THEN 1 END) * 100.0 / COUNT(u.round_id), 2) AS exhaustive_draw_rate,
    ROUND(COUNT(CASE WHEN u.won_type = 'draw' AND u.is_tenpai = 1 THEN 1 END) * 100.0 /
          NULLIF(COUNT(CASE WHEN u.won_type = 'draw' THEN 1 END), 0), 2) AS draw_tenpai_rate,
    ROUND(COUNT(CASE WHEN u.is_fulo = 1 THEN 1 END) * 100.0 / COUNT(u.round_id), 2) AS call_rate,
    ROUND(COUNT(CASE WHEN u.is_riichi = 1 THEN 1 END) * 100.0 / COUNT(u.round_id), 2) AS riichi_rate,
    ROUND(AVG(CASE WHEN u.won_seat = u.seat_index THEN u.win_turn END)::numeric, 2) AS avg_turns,
    ROUND(AVG(CASE WHEN u.won_seat = u.seat_index THEN u.delta_score END)::numeric, 0) AS avg_win_score,
    ROUND(AVG(CASE WHEN u.ron_seat = u.seat_index THEN ABS(u.delta_score) END)::numeric, 0) AS avg_deal_in_score,
    ROUND(AVG(CASE WHEN u.won_seat = u.seat_index
                   THEN u.count_dora + u.count_akadora + u.count_uradora + u.count_kitadora
              END)::numeric, 2) AS avg_baopai,
    ROUND(COUNT(CASE WHEN u.won_seat = u.seat_index AND u.is_riichi = 1 AND u.count_uradora > 0 THEN 1 END) * 100.0 /
          NULLIF(COUNT(CASE WHEN u.won_seat = u.seat_index AND u.is_riichi = 1 THEN 1 END), 0), 2) AS li_baopai_rate_pct,
    ROUND(COUNT(CASE WHEN u.babei_count > 0 THEN 1 END) * 100.0 / COUNT(u.round_id), 2) AS babei_rate_pct
  FROM player_rounds u
  JOIN mahjong.participants p ON u.player_id = p.account_id
  LEFT JOIN public.participant_data pd ON p.discord_id = pd.discord_id
  GROUP BY u.player_id, p.nickname, pd.profile_img
  ORDER BY total_rounds DESC;
$function$
;

CREATE OR REPLACE FUNCTION plazmaburst.get_tournament_player_stats(t_id uuid)
 RETURNS TABLE(player_id uuid, nickname text, avatar text, scores jsonb, details jsonb)
 LANGUAGE sql
 STABLE
 SET search_path TO 'plazmaburst', 'public'
AS $function$WITH 
-- 1. 提取有效数据并按玩家和模式分类聚合 (丢弃 snd)
player_category_raw AS (
    SELECT
        mgs.player_id,
        map.category,
        SUM(mgs.kills)::numeric AS kills,
        SUM(mgs.deaths)::numeric AS deaths,
        SUM(mgs.aces)::numeric AS aces,
        SUM(mgs.headshots)::numeric AS headshots,
        SUM(mgs.double_kills)::numeric AS double_kills,
        SUM(mgs.triple_kills)::numeric AS triple_kills,
        SUM(mgs.quad_kills)::numeric AS quad_kills,
        SUM(mgs.penta_kills)::numeric AS penta_kills
    FROM plazmaburst.match_game_stats mgs
    JOIN plazmaburst.match_games mg ON mgs.match_game_id = mg.id
    JOIN plazmaburst.matches m ON mg.match_id = m.id
    JOIN plazmaburst.maps map ON mg.map_id = map.id
    WHERE m.tournament_id = t_id
      AND map.category != 'snd'
      AND m.status = 'Completed' -- 确保只计算已完成的比赛
    GROUP BY mgs.player_id, map.category
),

-- 2. 套用你的该死的公式，并处理除零风险
category_scores AS (
    SELECT
        player_id,
        category,
        kills, deaths, aces, headshots, double_kills, triple_kills, quad_kills, penta_kills,
        (kills + 5.0 * aces + 1.2 * deaths + 10 * headshots) AS denominator,
        CASE
            WHEN (kills + 5.0 * aces + 1.2 * deaths) = 0 THEN 60.0
            ELSE 60.0 + 40.0 * ((kills + 5.0 * aces + 10 * headshots) / (kills + 5.0 * aces + 1.2 * deaths + 10 * headshots))
        END AS cat_score
    FROM player_category_raw
),

-- 3. 计算玩家的 Overall 总量与平均分要素
player_overall AS (
    SELECT
        player_id,
        SUM(kills) AS overall_kills,
        SUM(deaths) AS overall_deaths,
        SUM(aces) AS overall_aces,
        SUM(headshots) AS overall_headshots,
        SUM(double_kills) AS overall_double_kills,
        SUM(triple_kills) AS overall_triple_kills,
        SUM(quad_kills) AS overall_quad_kills,
        SUM(penta_kills) AS overall_penta_kills,
        SUM(cat_score) AS sum_cat_score,
        COUNT(category) AS played_categories_count
    FROM category_scores
    GROUP BY player_id
),

-- 4. 将分类数据聚合成 JSON 对象，方便前端直接使用
player_json_build AS (
    SELECT
        player_id,
        jsonb_object_agg(
            category,
            jsonb_build_object(
                'kills', kills, 'deaths', deaths, 'aces', aces, 
                'headshots', headshots, 'double_kills', double_kills, 
                'triple_kills', triple_kills, 'quad_kills', quad_kills, 
                'penta_kills', penta_kills
            )
        ) AS cat_details,
        jsonb_object_agg(category, cat_score) AS cat_scores
    FROM category_scores
    GROUP BY player_id
)

-- 5. 组装最终结果：拼接玩家信息，填充未玩过模式的默认值 (0)
SELECT
    p.id AS player_id,
    p.nickname,
    COALESCE(p.profile_img, p.profile_url, '') AS avatar,
    
    -- Scores JSON
    jsonb_build_object(
        'overall', CASE 
            WHEN po.played_categories_count = 0 THEN 0 
            ELSE po.sum_cat_score / GREATEST(3, po.played_categories_count) 
        END,
        'arena', COALESCE((pjb.cat_scores->>'arena')::numeric, 0),
        'rails', COALESCE((pjb.cat_scores->>'rails')::numeric, 0),
        'snipers', COALESCE((pjb.cat_scores->>'snipers')::numeric, 0),
        'rockets', COALESCE((pjb.cat_scores->>'rockets')::numeric, 0),
        'rays', COALESCE((pjb.cat_scores->>'rays')::numeric, 0)
    ) AS scores,
    
    -- Details JSON
    jsonb_build_object(
        'overall', jsonb_build_object(
            'kills', COALESCE(po.overall_kills, 0), 'deaths', COALESCE(po.overall_deaths, 0), 
            'aces', COALESCE(po.overall_aces, 0), 'headshots', COALESCE(po.overall_headshots, 0), 
            'double_kills', COALESCE(po.overall_double_kills, 0), 'triple_kills', COALESCE(po.overall_triple_kills, 0), 
            'quad_kills', COALESCE(po.overall_quad_kills, 0), 'penta_kills', COALESCE(po.overall_penta_kills, 0)
        ),
        'arena', COALESCE(pjb.cat_details->'arena', '{"kills":0,"deaths":0,"aces":0,"headshots":0,"double_kills":0,"triple_kills":0,"quad_kills":0,"penta_kills":0}'::jsonb),
        'rails', COALESCE(pjb.cat_details->'rails', '{"kills":0,"deaths":0,"aces":0,"headshots":0,"double_kills":0,"triple_kills":0,"quad_kills":0,"penta_kills":0}'::jsonb),
        'snipers', COALESCE(pjb.cat_details->'snipers', '{"kills":0,"deaths":0,"aces":0,"headshots":0,"double_kills":0,"triple_kills":0,"quad_kills":0,"penta_kills":0}'::jsonb),
        'rockets', COALESCE(pjb.cat_details->'rockets', '{"kills":0,"deaths":0,"aces":0,"headshots":0,"double_kills":0,"triple_kills":0,"quad_kills":0,"penta_kills":0}'::jsonb),
        'rays', COALESCE(pjb.cat_details->'rays', '{"kills":0,"deaths":0,"aces":0,"headshots":0,"double_kills":0,"triple_kills":0,"quad_kills":0,"penta_kills":0}'::jsonb)
    ) AS details

FROM player_overall po
JOIN plazmaburst.players p ON p.id = po.player_id
JOIN player_json_build pjb ON p.id = pjb.player_id
ORDER BY (po.sum_cat_score / GREATEST(3, po.played_categories_count)) DESC;$function$
;

