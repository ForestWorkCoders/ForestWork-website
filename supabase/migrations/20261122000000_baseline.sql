          WHERE (m.north_id IS NOT NULL)
        ), game_ranks AS (
         SELECT match_players.tournament_bind_id,
            match_players.account_id,
            match_players.score,
            rank() OVER (PARTITION BY match_players.uuid ORDER BY match_players.score DESC) AS game_rank,
            match_players.basepts,
            match_players.uma1,
            match_players.uma2,
            match_players.uma3,
            match_players.uma4
           FROM match_players
        ), game_points AS (
         SELECT game_ranks.tournament_bind_id,
            game_ranks.account_id,
            ((((game_ranks.score)::numeric - COALESCE(game_ranks.basepts, (25000)::numeric)) / 1000.00) +
                CASE game_ranks.game_rank
                    WHEN 1 THEN COALESCE(game_ranks.uma1, (15)::numeric)
                    WHEN 2 THEN COALESCE(game_ranks.uma2, (5)::numeric)
                    WHEN 3 THEN COALESCE(game_ranks.uma3, ('-5'::integer)::numeric)
                    WHEN 4 THEN COALESCE(game_ranks.uma4, ('-15'::integer)::numeric)
